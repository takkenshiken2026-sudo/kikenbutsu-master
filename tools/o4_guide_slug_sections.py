def _short_topic(title: str, slug: str) -> str:
    t = title.replace(EXAM_FULL, "").strip()
    for prefix in ("危険物取扱者試験", "危険物取扱者", "危険物"):
        t = t.strip(prefix).strip("の").strip("｜").strip()
    if not t or len(t) < 4:
        t = slug.replace("-", " ").replace("affiliate-", "").replace("field-", "")
    return t


def _section_opener(title: str, slug: str, section_index: int) -> str:
    topic = _short_topic(title, slug)
    patterns = (
        f"{topic}では、",
        f"{topic}を進めるうえで、",
        f"ここでは{topic}について、",
        f"{topic}の実務で押さえるのは、",
        f"まとめると{topic}では、",
    )
    return patterns[section_index % len(patterns)]


