def _field_context(slug: str) -> dict[str, str]:
    m = FIELD_SLUG_RE.match(slug)
    if not m:
        return {}
    fid, suffix = m.group(1), m.group(2)
    lines = FIELD_SUFFIX_LINES.get(suffix, FIELD_SUFFIX_LINES["basics"])
    return {
        "field_intro": FIELD_INTROS.get(fid, ""),
        "field_basics": lines.get("field_basics", ""),
        "field_frequent": lines.get("field_frequent", ""),
        "field_past": lines.get("field_past", ""),
        "field_cross": lines.get("field_cross", ""),
    }


def _finalize_body(body: str, ctx: dict[str, str]) -> str:
    text = body.strip()
    if len(text) < 72 or text.count("。") < 2:
        pad = BODY_PAD.format(**ctx)
        if pad not in text:
            text = text + pad
    return text


def slug_section_bodies(slug: str, genre: str, title: str) -> dict[str, str]:
    """見出し → 本文（記事ごとに固有）。"""
    outline = GENRE_OUTLINES.get(genre, GENRE_OUTLINES["学習計画"])
    headings: list[str] = list(outline.get("sections", []))  # type: ignore[arg-type]
    templates = GENRE_SECTION_TEMPLATES.get(genre, GENRE_SECTION_TEMPLATES["学習計画"])
    ctx = {
        "brand": BRAND,
        "official": OFFICIAL,
        **_field_context(slug),
    }
    result: dict[str, str] = {}
    extras = SLUG_SECTION_EXTRA.get(slug, {})
    topic = _short_topic(title, slug)
    for i, heading in enumerate(headings[: len(templates)]):
        ctx["focus"] = _section_opener(title, slug, i)
        body = templates[i].format(**ctx)
        if heading in extras:
            body = body + "\n\n" + extras[heading]
        if genre == "過去問活用" and i == 3 and heading not in extras:
            hint = _past_slug_hint(slug)
            if hint:
                body += " " + hint
        if genre == "学習計画" and i == 4 and heading not in extras:
            hint = _study_slug_hint(slug)
            if hint:
                body += " " + hint
        if i == len(headings[: len(templates)]) - 1 and topic not in body:
            body += (
                f" 関連する試験ガイドと{BRAND}の演習を組み合わせ、"
                f"{topic}の学習を完了させてください。"
            )
        result[heading] = _finalize_body(body, ctx)
    return result


