def main() -> int:
    if not CSV_PATH.is_file():
        print(f"入力がありません: {CSV_PATH}", file=sys.stderr)
        return 1

    text = CSV_PATH.read_text(encoding="utf-8-sig")
    reader = csv.DictReader(text.splitlines())
    fieldnames = list(reader.fieldnames or [])
    rows = list(reader)

    # 列を explanation の直後に挿入。
    for col in ("explanation_opposite", "explanation_correct"):
        if col not in fieldnames:
            idx = fieldnames.index("explanation") + 1
            fieldnames.insert(idx, col)

    by_id = {(r.get("id") or "").strip(): r for r in rows}
    applied = 0
    missing = []
    for rid, (correct, opposite) in ENRICH.items():
        if not correct and not opposite:
            continue  # placeholder guard rows
        row = by_id.get(rid)
        if row is None:
            missing.append(rid)
            continue
        changed = False
        if (row.get("explanation_correct") or "").strip() != correct:
            row["explanation_correct"] = correct
            changed = True
        if (row.get("explanation_opposite") or "").strip() != opposite:
            row["explanation_opposite"] = opposite
            changed = True
        if changed:
            applied += 1

    # 既存行に新列キーが無い場合の穴埋め。
    for r in rows:
        for col in fieldnames:
            r.setdefault(col, "")

    out = CSV_PATH.open("w", encoding="utf-8", newline="")
    writer = csv.DictWriter(out, fieldnames=fieldnames)
    writer.writeheader()
    writer.writerows(rows)
    out.close()

    print(f"適用: {applied} 行 / 対象定義: {len(ENRICH)}（プレースホルダ除く）")
    if missing:
        print(f"CSVに見つからないID: {missing}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
