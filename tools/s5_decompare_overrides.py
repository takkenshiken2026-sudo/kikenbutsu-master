from __future__ import annotations

import re

META_2COL_RE = re.compile(r"[^。]*2列比較[^。]*。?")


def scrub_meta(text: str) -> str:
    t = META_2COL_RE.sub("", text or "").strip()
    if not t.endswith("。"):
        t += "。"
    return t


def scrub_user_intent(text: str) -> str:
    t = (text or "").replace("使い分けも表で把握できます", "使い分けも本文で把握できます")
    t = t.replace("使い分けも表で把握", "使い分けも本文で把握")
    return t


def _s5(heading: str, intro: str, bullets: list[tuple[str, str]], example: str) -> dict[str, str]:
    body = intro + "\n\n" + "\n".join(f"**{b}** … {d}" for b, d in bullets)
    body += f"\n\nたとえば{example}"
    return {"section_5_heading": heading, "section_5_body": body}


